import { withLocalAssetBase } from "@/lib/utils";

export type WeaponClass = "KINETIC" | "RAPID" | "HEAVY" | "ENERGY" | "STRATEGIC";
export type WeaponModelKind = "pistol" | "ak-rifle" | "machine-gun" | "cannon" | "icbm";

export interface ArmoryWeaponSpec {
  id: string;
  slotNumber: number;
  code: string;
  serial: string;
  weaponClass: WeaponClass;
  classLabel: string;
  modelKind: WeaponModelKind;
  name: string;
  caliber: string;
  imagePath: string;
  pedestalImagePath?: string;
  fireRate: number; // shots/sec (0 if continuous beam or 1x rage)
  fireRateLabel?: string; // e.g., "BEAM" or "1x RAGE"
  projectilesPerShot: number;
  projectileLabel: string;
  damage: number;
  splashRadius: number;
  tracerLabel: string;
  tracerHex: string;
  unlockChapter: number;
  upgradeBaseCost: number;
  rageSkillName: string;
  rageSkillDescEn: string;
  rageSkillDescVi: string;
}

export const MAX_WEAPON_LEVEL = 10;
export const MAX_LOADOUT_SLOTS = 3;
export const DEFAULT_LOADOUT_IDS: string[] = ["pistol", "ak47", "shotgun"];

export function getWeaponUpgradeCost(weapon: ArmoryWeaponSpec, currentLevel: number): number {
  return weapon.upgradeBaseCost * currentLevel;
}

export function getWeaponStatsAtLevel(
  weapon: ArmoryWeaponSpec,
  level: number
): {
  damage: number;
  nextDamage: number;
  fireRate: number;
  nextFireRate: number;
} {
  const dmgMultiplier = 1 + (level - 1) * 0.1;
  const nextDmgMultiplier = 1 + level * 0.1;
  const rofBonus = weapon.fireRate > 0 ? (level - 1) * 0.35 : 0;
  const nextRofBonus = weapon.fireRate > 0 ? level * 0.35 : 0;

  return {
    damage: Number((weapon.damage * dmgMultiplier).toFixed(2)),
    nextDamage: Number((weapon.damage * nextDmgMultiplier).toFixed(2)),
    fireRate: Number((weapon.fireRate + rofBonus).toFixed(1)),
    nextFireRate: Number((weapon.fireRate + nextRofBonus).toFixed(1)),
  };
}

export function getWeaponImageUrl(weapon: ArmoryWeaponSpec, usePedestal = false): string {
  const rel = usePedestal && weapon.pedestalImagePath ? weapon.pedestalImagePath : weapon.imagePath;
  return withLocalAssetBase(rel);
}

